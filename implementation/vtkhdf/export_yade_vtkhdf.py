def export_vtkhdf(filename, display_group_names=None, display_group=None):
    """Export the current simulation state to an ON-DEM VTKHDF file (one timestep).

    Generated from schema: ../..
    Mapping file:          yade_mapping.json

    Parameters
    ----------
    filename : str
        Output file path (should end in .vtkhdf or .hdf).
    display_group_names : list of str, optional
        scene.display_group_names: one VTKHDF block per name, in this order.
    display_group : dict or callable, optional
        base_body.display_group of each body, an index into display_group_names:
        a dict {body_id: index} (bodies not in the dict get 0) or a callable
        body -> index. Requires display_group_names.

    Neither given: the default groups ['Points', 'Others'], spheres in Points and
    every other shape in Others. Names given without display_group: every body
    in the first group. Every group gets a block, also when it is empty.

    Raises ValueError (and writes no file) if display_group is given without
    display_group_names, if a name or an index is invalid, or if the scene
    cannot be written completely (mapping "_refuse_if", e.g. a periodic cell).
    """
    if O.periodic:
        raise ValueError('[export_vtkhdf] periodic scenes (O.periodic) are not supported yet: the periodic cell would not be written')
    global _DISPLAY_GROUP_NAMES, _DISPLAY_GROUP_SOURCE
    if display_group is not None and display_group_names is None:
        raise ValueError("[export_vtkhdf] display_group was given without display_group_names: "
                         "give the names of the groups it indexes (the defaults 'Points' / 'Others' "
                         "only go with the default rule)")
    if display_group_names is None:
        _DISPLAY_GROUP_NAMES = list(_DEFAULT_DISPLAY_GROUP_NAMES)
        _DISPLAY_GROUP_SOURCE = _default_display_group
    else:
        _DISPLAY_GROUP_NAMES = list(display_group_names)
        _DISPLAY_GROUP_SOURCE = display_group

    try:
        with h5py.File(filename, "w") as f:

            # 1. Bodies: /VTKHDF blocks (one per display group) + /ONDEM/Bodies
            n_bodies = _export_bodies(f)

            # 2. Scene metadata (includes display_group_names)
            _export_scene(f)

            # 3. Materials
            _export_materials(f)

            # 4. Interactions
            n_intrs = _export_interactions(f)

            # Top-level metadata
            f.attrs["file_format"]         = "ON-DEM VTKHDF"
            f.attrs["file_format_version"] = "0.2-draft"
            f.attrs["schema_dir"]          = "../.."
            f.attrs["mapping_file"]        = "yade_mapping.json"
    except Exception:
        # do not leave a half-written file behind
        if os.path.exists(filename):
            os.remove(filename)
        raise

    print(f"[export_vtkhdf] Exported {n_bodies} bodies in {len(_DISPLAY_GROUP_NAMES)} display group(s), "
          f"{n_intrs} interactions at t={O.time + (float(O.tags['ondem_time_offset']) if 'ondem_time_offset' in O.tags.keys() else 0.0):.6g} to '{filename}'")


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "output.vtkhdf"
    export_vtkhdf(out)
