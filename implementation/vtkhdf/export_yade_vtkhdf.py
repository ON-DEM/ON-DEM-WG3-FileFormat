# default display groups (decision 18): spheres -> Points, every other shape -> Others
_DEFAULT_DISPLAY_GROUP_NAMES = ["Points", "Others"]
_DISPLAY_GROUP_NAMES = list(_DEFAULT_DISPLAY_GROUP_NAMES)
_DISPLAY_GROUP_SOURCE = None

def _display_group_names():
    """scene.display_group_names for the current export."""
    return list(_DISPLAY_GROUP_NAMES)

def _default_display_group(b):
    """Default rule: 0 (Points) for spheres, 1 (Others) for every other shape."""
    return 0 if _shape_name(b) == "sphere" else 1

def _display_group(b):
    """base_body.display_group of body b: from the dict {body_id: index} or the
    callable set by export_vtkhdf; 0 (the first group) otherwise."""
    src = _DISPLAY_GROUP_SOURCE
    if src is None:
        return 0
    if callable(src):
        return src(b)
    return src.get(b.id, 0)

def _collect(items, fields):
    """Evaluate every getter of fields on every item; a failing getter gives None."""
    cols = {}
    for name, _h, _mandatory, get in fields:
        vals = []
        for it in items:
            try: vals.append(get(it))
            except Exception: vals.append(None)
        cols[name] = vals
    return cols


def _export_scene(f):
    """Write /ONDEM/Scene — generated from scene schema."""
    grp = f.require_group("ONDEM/Scene")

    #  units: List[str] 
    hdf5_write_field(grp, "units", "string_list", ['second', 'meter', 'kilogram'], scalar_as_dataset=False)

    #  timestep: float [T]
    hdf5_write_field(grp, "timestep", "scalar_float", O.dt, scalar_as_dataset=False)

    #  time: float [T]
    hdf5_write_field(grp, "time", "scalar_float", O.time + (float(O.tags['ondem_time_offset']) if 'ondem_time_offset' in O.tags.keys() else 0.0), scalar_as_dataset=False)

    # [optional] iteration: int [$-$]
    hdf5_write_field(grp, "iteration", "scalar_int", O.iter + (int(O.tags['ondem_iteration_offset']) if 'ondem_iteration_offset' in O.tags.keys() else 0), scalar_as_dataset=False)

    #  gravity: Vector3 [L/T²]
    hdf5_write_field(grp, "gravity", "vector3", _get_gravity(), scalar_as_dataset=False)

    # [optional] display_group_names: List[str] [$-$]
    hdf5_write_field(grp, "display_group_names", "string_list", _display_group_names(), scalar_as_dataset=False)

    # [mandatory] shape_names: List[str] [$-$]
    hdf5_write_field(grp, "shape_names", "string_list", _shape_names(), scalar_as_dataset=False)


def _export_materials(f):
    """Write /ONDEM/Materials — generated from materials schema."""
    mat_grp = f.require_group("ONDEM/Materials")
    seen_ids = set()
    for b in O.bodies:
        if b is None or b.material is None: continue   # clump bodies have no material
        mat = b.material
        if mat.id in seen_ids: continue
        seen_ids.add(mat.id)
        g = mat_grp.create_group(str(mat.id))
        g.attrs["schema_classes"] = 'linear_elastic_frictional_3D'

        # Extra YADE-specific attributes (not in schema but useful)
        try: g.create_dataset("label", data=str(mat.label if mat.label else '').encode("utf-8"))
        except: pass
        try: g.create_dataset("material_type", data=str(type(mat).__name__).encode("utf-8"))
        except: pass
        try: g.create_dataset("yade_poisson", data=np.float64(mat.poisson))
        except: pass

        # --- linear_elastic_frictional_3D: Material with linear-elastic behaviour and sliding friction. ---
        # [mandatory] id: int [$-$]
        try:
            hdf5_write_field(g, "id", "scalar_int", mat.id, scalar_as_dataset=True)
        except Exception as _e:
            print(f"[export_vtkhdf] Warning: material {mat.id}: mandatory field id not written ({_e})")

        # [mandatory] density: float [$ML^{-3}$]
        try:
            hdf5_write_field(g, "density", "scalar_float", mat.density, scalar_as_dataset=True)
        except Exception as _e:
            print(f"[export_vtkhdf] Warning: material {mat.id}: mandatory field density not written ({_e})")

        # [mandatory] normal_stiffness: float [$FL^{-1}$]
        try:
            hdf5_write_field(g, "normal_stiffness", "scalar_float", mat.young, scalar_as_dataset=True)
        except Exception as _e:
            print(f"[export_vtkhdf] Warning: material {mat.id}: mandatory field normal_stiffness not written ({_e})")

        # [mandatory] shear_stiffness: float [$FL^{-1}$]
        try:
            hdf5_write_field(g, "shear_stiffness", "scalar_float", mat.young * mat.poisson, scalar_as_dataset=True)
        except Exception as _e:
            print(f"[export_vtkhdf] Warning: material {mat.id}: mandatory field shear_stiffness not written ({_e})")

        # [mandatory] shear_friction: float [$-$]
        try:
            hdf5_write_field(g, "shear_friction", "scalar_float", float(np.tan(mat.frictionAngle)), scalar_as_dataset=True)
        except Exception as _e:
            print(f"[export_vtkhdf] Warning: material {mat.id}: mandatory field shear_friction not written ({_e})")

        # [mandatory] shear_damping: float [$MT^{-1}$]
        try:
            hdf5_write_field(g, "shear_damping", "scalar_float", 0.0, scalar_as_dataset=True)
        except Exception as _e:
            print(f"[export_vtkhdf] Warning: material {mat.id}: mandatory field shear_damping not written ({_e})")


